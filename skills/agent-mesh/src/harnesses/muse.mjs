/**
 * Muse Code (`muse`): Meta's interactive terminal coding agent (`muse --version` -> "Muse Code 1.4.8").
 *
 * Integration surface found on this machine (see docs/ADAPTERS.md "Muse"):
 * - hooks and MCP servers are shipped as PLUGIN BUNDLES (`.muse-plugin/plugin.json`) installed with
 *   `muse plugins install <dir> --scope user|project` and trusted with `muse plugins approve <id>`; there is no
 *   hand-edited hooks file. Hook events are Claude-compatible (SessionStart, UserPromptSubmit, Stop, SessionEnd,
 *   ...), additionalContext output is honored, and every hook needs its own source file.
 * - sessions live in `~/.local/share/muse/session-index.db` (title / session_name), config in `~/.config/muse`.
 * - the real process is `muse-bin-<version>.exe`, launched through muse.cmd -> PowerShell launcher.
 */

import { join, dirname } from "node:path";
import { homedir } from "node:os";
import { existsSync, mkdirSync, writeFileSync, readFileSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { readSqliteRow, execSqlite } from "./shared/sqlite.mjs";
import { DEFAULT_TTL_MS, classifyCmdline, getMeshHome, firstPositional as sharedFirstPositional } from "./shared/process.mjs";
import { diagnoseResult, MCP_SERVER_NAME } from "./shared/install.mjs";

const ID = "muse";
const HOOK_PLUGIN = "agent-mesh";
const MCP_PLUGIN = "agent-mesh-mcp";

// ---- locating the CLI -----------------------------------------------------------------------------------

/**
 * The muse executable: MESH_MUSE_BIN, else the versioned `muse-bin-*.exe` next to `muse.cmd` on PATH (talking to
 * the real binary avoids the launcher's update check), else `muse` through the shell.
 */
export function resolveMuseBin(env = process.env) {
  if (env.MESH_MUSE_BIN) return { bin: env.MESH_MUSE_BIN, shell: false };
  const names = process.platform === "win32" ? ["muse.cmd", "muse.exe"] : ["muse"];
  for (const dir of String(env.PATH || env.Path || "").split(process.platform === "win32" ? ";" : ":")) {
    if (!dir || !names.some((n) => existsSync(join(dir, n)))) continue;
    try {
      const version = readFileSync(join(dir, ".muse-version"), "utf8").trim();
      const exact = join(dir, `muse-bin-${version}.exe`);
      if (existsSync(exact)) return { bin: exact, shell: false };
      const newest = readdirSync(dir).filter((f) => /^muse-bin-.*\.exe$/.test(f)).sort().pop();
      if (newest) return { bin: join(dir, newest), shell: false };
    } catch {}
    return { bin: join(dir, names.find((n) => existsSync(join(dir, n)))), shell: process.platform === "win32" };
  }
  return { bin: "muse", shell: process.platform === "win32" };
}

/** Runs the muse CLI; throws on failure. cwd matters for project scope. */
function muse(args, { cwd, env = process.env } = {}) {
  const { bin, shell } = resolveMuseBin(env);
  return execFileSync(bin, args, { cwd, env, encoding: "utf8", timeout: 60000, windowsHide: true, shell, stdio: ["ignore", "pipe", "pipe"] });
}

const museAvailable = () => {
  try {
    muse(["--version"]);
    return true;
  } catch {
    return false;
  }
};

// ---- plugin bundles ---------------------------------------------------------------------------------------

const bundleDir = (name) => join(getMeshHome(), ".agent-mesh", "muse-plugin", name);

function writeBundle(name, manifest, files) {
  const dir = bundleDir(name);
  mkdirSync(join(dir, ".muse-plugin"), { recursive: true });
  writeFileSync(join(dir, ".muse-plugin", "plugin.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), content, "utf8");
  }
  return dir;
}

const manifestBase = (name, displayName, description, capabilities) => ({
  schemaVersion: 1,
  name,
  displayName,
  version: "1.0.0",
  description,
  compat: { source: "native", manifestDir: ".muse-plugin" },
  capabilities: { skills: [], commands: [], hooks: [], mcpServers: [], reminders: [], ...capabilities },
});

const HOOKS = [
  { id: "session-start", event: "SessionStart", arg: "SessionStart" },
  { id: "prompt-submit", event: "UserPromptSubmit", arg: "UserPromptSubmit" },
  { id: "stop", event: "Stop", arg: "Stop" },
  { id: "session-end", event: "SessionEnd", arg: "SessionEnd" },
];

/** Hook bundle: each hook gets its own wrapper file (Muse rejects two hooks sharing a source). */
function hookBundle(presenceScript) {
  const target = pathToFileURL(presenceScript).href;
  const files = {};
  for (const h of HOOKS) {
    files[`hooks/${h.id}.mjs`] =
      `// Generated by agent-mesh: runs the shared presence hook for ${h.event}.\n` +
      `process.argv.push("--event", ${JSON.stringify(h.arg)}, "--harness", "muse");\n` +
      `await import(${JSON.stringify(target)});\n`;
  }
  const manifest = manifestBase(HOOK_PLUGIN, "Agent Mesh", "Presence and mail delivery for the agent mesh.", {
    hooks: HOOKS.map((h) => ({ id: h.id, event: h.event, command: ["node", `hooks/${h.id}.mjs`], timeoutMs: 10000 })),
  });
  return { manifest, files };
}

function mcpBundle(script) {
  const manifest = manifestBase(MCP_PLUGIN, "Agent Mesh MCP", "mesh_send / mesh_ask / mesh_inbox / mesh_status tools.", {
    mcpServers: [{ id: MCP_SERVER_NAME, transport: "stdio", command: ["node", script.replace(/\\/g, "/"), "--harness", ID] }],
  });
  return { manifest, files: {} };
}

const scopeArgs = (p) => (p.scope === "project" ? ["--scope", "project"] : ["--scope", "user"]);

/** Installs (replacing any previous version) and approves one bundle. */
function installBundle(name, built, p) {
  if (!museAvailable()) return { ok: false, error: "muse CLI not found (set MESH_MUSE_BIN or add muse to PATH)", modified: false };
  const dir = writeBundle(name, built.manifest, built.files);
  try {
    try { muse(["plugins", "remove", name], { cwd: p.root }); } catch {} // not installed yet
    muse(["plugins", "install", dir, ...scopeArgs(p)], { cwd: p.root });
    muse(["plugins", "approve", name], { cwd: p.root });
    return { ok: true, modified: true };
  } catch (err) {
    return { ok: false, error: `muse plugins install failed: ${String(err.stderr || err.message).trim().slice(0, 300)}`, modified: false };
  }
}

function removeBundle(name, p) {
  if (!museAvailable()) return { ok: true, modified: false };
  try {
    return { ok: true, modified: /removed/.test(muse(["plugins", "remove", name], { cwd: p.root })) };
  } catch {
    return { ok: true, modified: false }; // not installed
  }
}

function bundleInstalled(name, p) {
  try {
    const list = JSON.parse(muse(["plugins", "list", "--json"], { cwd: p.root }));
    return (list.plugins || []).some((e) => e.record?.id === name && e.record?.enabled !== false);
  } catch {
    return false;
  }
}

const resolvePaths = ({ global, root }) => ({ targetPath: join(homedir(), ".local", "share", "muse", "plugins"), scope: global ? "user" : "project", root });

// ---- session names ------------------------------------------------------------------------------------------

/** Muse session index (MESH_MUSE_DB overrides, used by tests). */
const dbPath = () => process.env.MESH_MUSE_DB || join(homedir(), ".local", "share", "muse", "session-index.db");

function resolveName({ sessionId }) {
  const r = readSqliteRow(dbPath(), "SELECT session_name, title FROM sessions WHERE session_id = ?", sessionId);
  return r?.session_name || r?.title || null;
}

// ---- process classification -------------------------------------------------------------------------------

const VALUE_FLAGS = new Set([
  "--agents", "--provider", "--preset", "--model", "--contributor-mode", "-c", "--config", "--reasoning-effort",
  "--effort", "--base-url", "--image", "--workspace", "--worktree-base", "--worktree-existing", "--approval-mode",
  "--permission-profile", "--approval-judge", "--sandbox-network", "--echo-delay-ms",
]);
// Subcommands that never host an interactive session. `resume` (and a bare prompt) is the TUI.
const NON_SESSION = new Set([
  "exec", "config", "export", "trace", "model-profile", "skills", "voice", "plugins", "sandbox", "schema", "serve",
  "session-message", "mcp", "auth", "login", "logout", "init", "workflows", "help",
]);
const firstPositional = (cmdline) => sharedFirstPositional(cmdline, { valueFlags: VALUE_FLAGS });

function isInteractiveTui(cmdline) {
  if (!cmdline) return false;
  const p = firstPositional(cmdline);
  return !p.exits && !NON_SESSION.has(p.token);
}

/** `muse exec` runs hooks in its own process and is not a user terminal. */
function classifyProcess(cmdline) {
  const cls = classifyCmdline(cmdline);
  return { ...cls, background: cls.background || firstPositional(cmdline).token === "exec" };
}

